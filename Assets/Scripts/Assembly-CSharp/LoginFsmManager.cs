	private IEnumerator StartDownloadServerInfoWWW(Action callback)
	{
		string rawPath = Common.GetGameXmlPath();
		string url = rawPath;
		if (!url.Contains("://"))
		{
			url = "file:///" + Uri.EscapeUriString(url);
		}
		UnityEngine.Debug.Log("load server info url:" + url);
		WWW www = new WWW(url);
		float waitingTime = 0f;
		bool bTimeout = false;

		while (!www.isDone)
		{
			waitingTime += Time.deltaTime;
			if (waitingTime > 10f)
			{
				bTimeout = true;
				break;
			}
			yield return null;
		}

		if (string.IsNullOrEmpty(www.error) && !bTimeout)
		{
			SaveXml(www.text);
			if (callback != null)
			{
				callback.Invoke();
			}
		}
		else
		{
			UnityEngine.Debug.LogError("load server info xml failed: " + www.error + ". Attempting local File fallback.");
			if (System.IO.File.Exists(rawPath))
			{
				string xmlContent = System.IO.File.ReadAllText(rawPath);
				SaveXml(xmlContent);
				if (callback != null)
				{
					callback.Invoke();
				}
			}
		}
		www.Dispose();
	}

